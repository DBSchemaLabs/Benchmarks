#!/usr/bin/env bash
# Database-only expand/contract migration under concurrent writes.
# macOS + PostgreSQL 16. WARNING: recreates the dedicated schema_labs_e3 database.
set -euo pipefail

HOST=/tmp
PORT=5499
USER=pg
DB=schema_labs_e3
BATCH_SIZE=100000
INITIAL_ROWS=2000000
WORKDIR="$(mktemp -d "${TMPDIR:-/tmp}/schema-labs-e3.XXXXXX")"
STOP_FILE="$WORKDIR/stop-writer"
WRITER_LOG="$WORKDIR/writer.log"
WRITER_PID=

export PGHOST="$HOST" PGPORT="$PORT" PGUSER="$USER" PGDATABASE="$DB"
psql_e3() { psql -X -v ON_ERROR_STOP=1 "$@"; }
now() { python3 -c 'import time; print(time.monotonic())'; }
elapsed() { python3 -c 'import sys; print(f"{float(sys.argv[2])-float(sys.argv[1]):.3f}")' "$1" "$2"; }
cleanup() {
  touch "$STOP_FILE"
  if [[ -n "$WRITER_PID" ]]; then
    wait "$WRITER_PID" || true
  fi
  echo "Writer log: $WRITER_LOG"
}
trap cleanup EXIT

command -v python3 >/dev/null || { echo 'python3 is required' >&2; exit 1; }
command -v psql >/dev/null || { echo 'PostgreSQL client tools are required' >&2; exit 1; }
command -v dropdb >/dev/null || { echo 'dropdb is required' >&2; exit 1; }
command -v createdb >/dev/null || { echo 'createdb is required' >&2; exit 1; }

echo "Recreating dedicated experiment database: $DB"
dropdb --if-exists "$DB"
createdb "$DB"

psql_e3 <<'SQL'
\timing on
CREATE TABLE orders (
  id bigint GENERATED BY DEFAULT AS IDENTITY PRIMARY KEY,
  status text NOT NULL
);
INSERT INTO orders(status)
SELECT (ARRAY['pending','paid','shipped','cancelled'])[1 + (g % 4)]
FROM generate_series(1, 2000000) AS g;
ANALYZE orders;
SELECT count(*) AS initial_rows FROM orders;

-- Expand: metadata-only nullable column, then synchronization.
CREATE TABLE order_status (
  id smallint PRIMARY KEY,
  name text NOT NULL UNIQUE
);
INSERT INTO order_status(id, name) VALUES
  (1, 'pending'), (2, 'paid'), (3, 'shipped'), (4, 'cancelled');
ALTER TABLE orders ADD COLUMN status_id smallint;

CREATE FUNCTION orders_sync() RETURNS trigger LANGUAGE plpgsql AS $$
BEGIN
  SELECT id INTO NEW.status_id FROM order_status WHERE name = NEW.status;
  IF NEW.status_id IS NULL THEN
    RAISE EXCEPTION 'unknown status: %', NEW.status;
  END IF;
  RETURN NEW;
END;
$$;
CREATE TRIGGER orders_sync_trigger
BEFORE INSERT OR UPDATE OF status ON orders
FOR EACH ROW EXECUTE FUNCTION orders_sync();
SQL

# The writer stays active through the final transactional swap.
# Each statement runs with ON_ERROR_STOP and a short statement timeout.
(
  i=0
  while [[ ! -e "$STOP_FILE" ]]; do
    i=$((i + 1))
    id=$(( (i % INITIAL_ROWS) + 1 ))
    if ! psql_e3 -q -c "SET statement_timeout = '15s'; INSERT INTO orders(status) VALUES ('paid'); UPDATE orders SET status='shipped' WHERE id=$id;" >>"$WRITER_LOG" 2>&1; then
      echo "Writer failed at iteration $i" >>"$WRITER_LOG"
      exit 1
    fi
    sleep 0.02
  done
  echo "Writer completed $i iterations" >>"$WRITER_LOG"
) &
WRITER_PID=$!

sleep 0.2
echo '--- Batched backfill with concurrent writer ---'
start=$(now)
for ((lo=0; lo<INITIAL_ROWS; lo+=BATCH_SIZE)); do
  hi=$((lo + BATCH_SIZE))
  psql_e3 -q -c "
    UPDATE orders AS o
       SET status_id = s.id
      FROM order_status AS s
     WHERE o.status = s.name
       AND o.id > $lo AND o.id <= $hi
       AND o.status_id IS NULL;"
done
end=$(now)
echo "Backfill duration: $(elapsed "$start" "$end") seconds"

# Verify both missing values and incorrect mappings while writer is active.
psql_e3 <<'SQL'
SELECT count(*) AS inconsistent_rows
FROM orders o
LEFT JOIN order_status s ON s.id = o.status_id
WHERE o.status_id IS NULL OR s.name IS DISTINCT FROM o.status;

-- Validate without rewriting the table; the writer remains active.
ALTER TABLE orders ADD CONSTRAINT orders_status_id_nn
  CHECK (status_id IS NOT NULL) NOT VALID;
ALTER TABLE orders VALIDATE CONSTRAINT orders_status_id_nn;
ALTER TABLE orders ADD CONSTRAINT orders_status_id_fk
  FOREIGN KEY (status_id) REFERENCES order_status(id) NOT VALID;
ALTER TABLE orders VALIDATE CONSTRAINT orders_status_id_fk;
ANALYZE orders;
SQL

# Fail on an inconsistent result rather than merely printing it.
inconsistent=$(psql_e3 -At -c "SELECT count(*) FROM orders o LEFT JOIN order_status s ON s.id=o.status_id WHERE o.status_id IS NULL OR s.name IS DISTINCT FROM o.status")
if [[ "$inconsistent" != '0' ]]; then
  echo "ERROR: $inconsistent inconsistent rows" >&2
  exit 1
fi

# The lock_timeout limits waiting for the cutover lock, not the blocking
# experienced by other sessions after that lock is acquired.
echo '--- Transactional cutover (writer is still active) ---'
start=$(now)
psql_e3 <<'SQL'
BEGIN;
SET LOCAL lock_timeout = '2s';
ALTER TABLE orders RENAME TO orders_base;
DROP TRIGGER orders_sync_trigger ON orders_base;
ALTER TABLE orders_base DROP COLUMN status;

CREATE VIEW orders AS
SELECT b.id, s.name AS status
FROM orders_base b JOIN order_status s ON s.id = b.status_id;

CREATE FUNCTION orders_view_dml() RETURNS trigger LANGUAGE plpgsql AS $$
DECLARE
  sid smallint;
BEGIN
  IF TG_OP IN ('INSERT', 'UPDATE') THEN
    SELECT id INTO sid FROM order_status WHERE name = NEW.status;
    IF sid IS NULL THEN
      RAISE EXCEPTION 'unknown status: %', NEW.status;
    END IF;
  END IF;

  IF TG_OP = 'INSERT' THEN
    IF NEW.id IS NULL THEN
      INSERT INTO orders_base(status_id) VALUES (sid) RETURNING id INTO NEW.id;
    ELSE
      INSERT INTO orders_base(id, status_id) VALUES (NEW.id, sid);
    END IF;
    RETURN NEW;
  ELSIF TG_OP = 'UPDATE' THEN
    IF NEW.id IS DISTINCT FROM OLD.id THEN
      RAISE EXCEPTION 'changing orders.id is not supported by compatibility view';
    END IF;
    UPDATE orders_base SET status_id = sid WHERE id = OLD.id;
    RETURN NEW;
  ELSE
    DELETE FROM orders_base WHERE id = OLD.id;
    RETURN OLD;
  END IF;
END;
$$;
CREATE TRIGGER orders_view_dml_trigger
INSTEAD OF INSERT OR UPDATE OR DELETE ON orders
FOR EACH ROW EXECUTE FUNCTION orders_view_dml();
COMMIT;
SQL
end=$(now)
echo "Cutover transaction duration (client observed): $(elapsed "$start" "$end") seconds"

# Exercise the compatibility view while the writer is still running.
psql_e3 <<'SQL'
INSERT INTO orders(status) VALUES ('pending') RETURNING id, status;
UPDATE orders SET status = 'paid' WHERE id = 1;
SELECT * FROM orders WHERE id = 1;
EXPLAIN (ANALYZE, BUFFERS) SELECT count(*) FROM orders WHERE status = 'paid';
SELECT count(*) AS paid_rows FROM orders WHERE status = 'paid';
SELECT count(*) AS total_rows FROM orders;
SQL

touch "$STOP_FILE"
wait "$WRITER_PID"
WRITER_PID=
echo '--- Writer results ---'
tail -n 5 "$WRITER_LOG"
echo "Writer log: $WRITER_LOG"
